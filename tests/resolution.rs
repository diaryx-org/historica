/// The corpus is not a fixture somebody generated: it is what an editor and a
/// checksum program print.
///
/// `tests/by-hand.sh` is decision 0032's tool-less merge as a list of
/// commands, and what it builds is this directory, byte for byte. Holding the
/// two together is what keeps the corpus honest — a hand-written fixture that
/// quietly stopped being writable by hand would prove nothing.
#[test]
fn the_corpus_is_what_an_editor_and_a_checksum_produce() {
    let scratch = Path::new(env!("CARGO_TARGET_TMPDIR")).join("by-hand-corpus");
    let _ = fs::remove_dir_all(&scratch);
    fs::create_dir_all(&scratch).expect("a scratch directory");
    let script = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/by-hand.sh");
    let built = std::process::Command::new("sh")
        .arg(&script)
        .arg(scratch.join("history"))
        .output()
        .expect("a shell");
    assert!(
        built.status.success(),
        "{}",
        String::from_utf8_lossy(&built.stderr)
    );

    let written: BTreeMap<String, RevisionId> = manifest()
        .into_keys()
        .filter(|name| name.starts_with("revisions/") || name.starts_with("operations/"))
        .map(|name| {
            let bytes = fs::read(scratch.join("history").join(&name))
                .unwrap_or_else(|_| panic!("the script wrote {name}"));
            (name, digest(&bytes))
        })
        .collect();
    for (name, produced) in &written {
        assert_eq!(digest(&read(name)), *produced, "{name}");
    }
    assert_eq!(written.len(), 11, "one file per document in the corpus");
}

/// The store carries the description of itself that makes "readable without
/// the tool" true, so the examples in it are corpus files rather than prose
/// somebody typed and nobody checked again.
#[test]
fn the_format_a_store_explains_itself_with_quotes_the_corpus_verbatim() {
    let explained = historica::store::FORMAT_NOTE;
    for name in [
        "revisions/01-root.rev.txt",
        "operations/03-notes.ops.txt",
        "operations/04-notes.ops.txt",
    ] {
        let text = String::from_utf8(read(name)).expect("a corpus file is UTF-8");
        // Indented by two, and blank lines left blank rather than indented.
        let quoted: String = text
            .lines()
            .map(|line| {
                if line.is_empty() {
                    "\n".to_owned()
                } else {
                    format!("  {line}\n")
                }
            })
            .collect();
        assert!(explained.contains(&quoted), "{name} is not quoted as it is");
    }

    // And every digest it prints is one this corpus actually holds, so a
    // reader following the example lands on the file it names.
    let held: BTreeMap<RevisionId, String> = manifest()
        .into_iter()
        .map(|(name, digest)| (digest, name))
        .collect();
    for word in explained.split(|c: char| !c.is_ascii_hexdigit()) {
        if word.len() != 64 {
            continue;
        }
        let digest: RevisionId = word.parse().expect("64 hexadecimal characters");
        assert!(held.contains_key(&digest), "{word} names nothing here");
    }
}

#[test]
fn every_invalid_resolution_is_refused_for_its_own_reason() {
    for (name, wanted) in invalid() {
        let bytes = read(&format!("invalid/{name}"));
        let error = ResolutionDocument::parse(&bytes)
            .map(|document| document.write())
            .expect_err(&format!("{name} should be refused"));
        assert_eq!(
            std::mem::discriminant(&error.kind),
            std::mem::discriminant(&wanted),
            "{name}: refused as {:?}, wanted {wanted:?}",
            error.kind
        );
    }
}

/// One invalid spelling per rule the grammar pins.
fn invalid() -> Vec<(&'static str, ParseErrorKind)> {
    vec![
        ("adjacent-keeps.ops.txt", ParseErrorKind::AdjacentKeeps),
        ("adjacent-inserts.ops.txt", ParseErrorKind::AdjacentInserts),
        ("empty-keep.ops.txt", ParseErrorKind::EmptyKeep),
        ("empty-insert.ops.txt", ParseErrorKind::EmptyInsert),
        ("no-pieces.ops.txt", ParseErrorKind::NoOperations),
        (
            "insert-with-position.ops.txt",
            ParseErrorKind::ResolutionInsertWithPosition {
                found: String::new(),
            },
        ),
        (
            "keep-without-result.ops.txt",
            ParseErrorKind::MissingHeader { key: "result" },
        ),
        (
            "malformed-keep.ops.txt",
            ParseErrorKind::UnknownOperation {
                found: String::new(),
            },
        ),
        (
            "malformed-keep-digest.ops.txt",
            ParseErrorKind::MalformedDigest {
                key: "keep",
                found: String::new(),
            },
        ),
    ]
}
